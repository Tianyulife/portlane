import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const source=readFileSync(new URL('../Sources/IndieRuntime/SteamLaunchRelay.swift',import.meta.url),'utf8');
const script=source.match(/installation = #"""([\s\S]*?)"""#/)[1];
let now=1000, timer;
const calls=[];
const apps={RunGame(...args){calls.push({receiver:this,args});return 'original';}};
const original=apps.RunGame;
const window={SteamClient:{Apps:apps}};
const context=vm.createContext({window,Date:{now:()=>now},setInterval:fn=>(timer=fn,1),clearInterval(){}});
vm.runInContext(script,context);
const relay=window.__mguLaunchRelay;
relay.configure([2358720,2001120]);
apps.RunGame('2358720','',-1,0);
apps.RunGame('2358720','',-1,0);
assert.deepEqual(Array.from(relay.take().appIDs),[2358720],'A double click must create only one request');
assert.equal(calls.length,0,'Managed Play must be intercepted before native process creation');
relay.complete(2358720);
apps.RunGame('2358720');
assert.deepEqual(Array.from(relay.take().appIDs),[2358720]);
assert.equal(apps.RunGame('570','arg',2,1),'original');
assert.deepEqual(calls[0].args,['570','arg',2,1]);
assert.equal(calls[0].receiver,apps,'Preserve native method receiver for unmanaged games');
apps.RunGame('12345678901234567');
assert.equal(calls.length,2,'Non-Steam shortcut GameIDs must not be coerced into AppIDs');
vm.runInContext(script,context);
assert.equal(window.__mguLaunchRelay,relay,'Polling must not reinstall or reset queued requests');
now+=16000;
apps.RunGame('2001120');
assert.equal(calls.length,3,'An expired host cannot hold Steam Play indefinitely');
timer();
assert.equal(apps.RunGame,original,'Expired hooks restore official Steam behaviour');
vm.runInContext(script,context);
assert.notEqual(window.__mguLaunchRelay,relay,'Reconnect supports a fresh Steam context');
window.__mguLaunchRelay.dispose();
assert.equal(apps.RunGame,original);
const readonly={RunGame:original};Object.freeze(readonly);
assert.throws(()=>vm.runInContext(script,vm.createContext({window:{SteamClient:{Apps:readonly}},Date,setInterval:()=>1,clearInterval(){}})));
console.log('Steam Play relay: interception, deduplication, passthrough, lease expiry and reconnect passed');
